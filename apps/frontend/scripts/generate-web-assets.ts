/** The mark is 354 x 425 units centred on (627, 627); a square frame keeps it centred. */
function squareViewBox(paddingRatio: number): string {
  const side = 425 * (1 + paddingRatio);
  const origin = 627 - side / 2;
  return `${origin} ${origin} ${side} ${side}`;
}

/**
 * SVG favicon with a transparent background. The ink follows the browser theme so the mark
 * stays visible on light and dark tabs.
 */
export function faviconSvg(): string {
  // Laid out on the 32px grid browsers use for high-density tabs; it scales cleanly to 16px.
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${pixelGridViewBox(32)}">`,
    `<style>g{fill:${MARK_INK}}[stroke]{stroke:${MARK_INK}}@media (prefers-color-scheme:dark){g{fill:${MARK_INK_ON_DARK}}[stroke]{stroke:${MARK_INK_ON_DARK}}}</style>`,
    hintedMarkBody(MARK_INK, 32),
    '</svg>\n',
  ].join('');
}

/** Mark bounds in opensignet-logo.svg units. */
const MARK_LEFT = 450;
const MARK_TOP = 414.5;
const MARK_HEIGHT = 425;
/** Share of a small icon's height the mark fills, leaving even breathing room like other tab icons. */
const ICON_FILL = 0.875;

/**
 * A square frame that puts the mark on whole pixels at `size`: the mark is an integer number of
 * pixels tall and starts on a pixel boundary, so its straight edges stay crisp instead of blurring
 * across two pixels.
 */
function pixelGridViewBox(size: number): string {
  const height = Math.round(size * ICON_FILL);
  const top = Math.floor((size - height) / 2);
  const unitsPerPixel = MARK_HEIGHT / height;
  // The mark's vertical axis (x = 627) lands on the centre of a pixel column, so the one-pixel stem
  // fills exactly one column and both halves stay mirror-symmetric.
  const axis = Math.floor(size / 2) - 0.5;
  const left = axis - (627 - MARK_LEFT) / unitsPerPixel;
  const x = MARK_LEFT - left * unitsPerPixel;
  const y = MARK_TOP - top * unitsPerPixel;
  return `${x} ${y} ${size * unitsPerPixel} ${size * unitsPerPixel}`;
}

/**
 * The mark with small-size hinting: at 16 and 32 pixels the thin centre stem would render below one
 * pixel and fade to grey, so only the stem gains a matching outline. Larger sizes use the exact
 * geometry.
 */
function hintedMarkBody(ink: string, size: number): string {
  const body = markSvgBody(ink);
  const minimumStemPixels = size <= 32 ? 1 : 0;
  if (!minimumStemPixels) return body;
  const unitsPerPixel = MARK_HEIGHT / Math.round(size * ICON_FILL);
  const stemUnits = 633.9 - 620.1;
  const stroke = Math.max(0, minimumStemPixels * unitsPerPixel - stemUnits);
  const stemPath = body.match(/<path d="M 610\.35[^"]*"\/>/)?.[0];
  assert.ok(stemPath, 'Mark stem path not found');
  return body.replace(
    stemPath,
    stemPath.replace(
      '/>',
      ` stroke="${ink}" stroke-width="${stroke.toFixed(2)}" stroke-linejoin="round"/>`,
    ),
  );
}

function pixelGridMarkSvg(size: number): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${pixelGridViewBox(size)}">${hintedMarkBody(MARK_INK, size)}</svg>`;
}

/** A tight, transparent mark for headers, in one ink. */
export function markSvg(ink: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="450 414.5 354 425">${markSvgBody(ink)}</svg>\n`;
}

function solidMarkSvg(paddingRatio: number, background?: string): string {
  const viewBox = squareViewBox(paddingRatio);
  const [x, y, side] = viewBox.split(' ');
  const fill = background
    ? `<rect x="${x}" y="${y}" width="${side}" height="${side}" fill="${background}"/>`
    : '';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${fill}${markSvgBody(MARK_INK)}</svg>`;
}

export async function generateWebAssets({ refresh = [] }: { refresh?: readonly string[] } = {}) {
  const sharp = loadSharp();
  const refreshed = new Set([...mutable, ...refresh]);
  const manifest = readAssetManifest();
  for (const [file, hash] of Object.entries(manifest.files)) {
    if (refreshed.has(file)) continue;
    assert.equal(
      assetHash(file, readFileSync(resolve(repositoryRoot, file))),
      hash,
      `Original changed: ${file}`,
    );
  }

  const original = resolve(repositoryRoot, 'brand/social/opensignet-social-card.png');
  const metadata = await sharp(original).metadata();
  assert.equal(metadata.hasAlpha, false, 'Do not silently discard transparency');
  const social = await sharp(original)
    .jpeg({ quality: 98, chromaSubsampling: '4:4:4', mozjpeg: true })
    .toBuffer();
  assert.ok(social.length < 600_000, 'Social delivery image exceeds compatibility budget');
  const encoded = await sharp(social).metadata();
  assert.equal(encoded.width, metadata.width);
  assert.equal(encoded.height, metadata.height);

  const files = new Map<string, Buffer>();
  files.set('brand/social/opensignet-social-card.jpg', social);
  files.set('brand/icons/favicon.svg', Buffer.from(faviconSvg()));
  // Transparent PNG fallbacks render the vector mark directly at each size (no resampling).
  const render = (svg: string, size: number) =>
    sharp(Buffer.from(svg.replace('<svg ', `<svg width="${size}" height="${size}" `)))
      .png({ compressionLevel: 9, adaptiveFiltering: true })
      .toBuffer();
  // Each favicon size is laid out on its own pixel grid with even breathing room.
  for (const size of [16, 32, 48, 96]) {
    files.set(`brand/icons/favicon-${size}.png`, await render(pixelGridMarkSvg(size), size));
  }
  files.set('brand/icons/icon-192.png', await render(solidMarkSvg(0.12), 192));
  files.set('brand/icons/icon-512.png', await render(solidMarkSvg(0.12), 512));
  // iOS fills transparent touch icons with black, so this one is opaque on a light field.
  files.set(
    'brand/icons/apple-touch-icon-180.png',
    await render(solidMarkSvg(0.7, '#ffffff'), 180),
  );
  // Android maskable icons are cropped to a circle: an opaque warm field keeps the mark inside
  // the 80% safe zone (mark height is half the canvas).
  files.set('brand/icons/icon-maskable-512.png', await render(solidMarkSvg(1, '#eeede7'), 512));

  // The ICO directory wraps the transparent PNG frames byte-for-byte.
  const images = [16, 32, 48].map((size) => {
    const bytes = files.get(`brand/icons/favicon-${size}.png`);
    assert.ok(bytes);
    assert.equal(bytes.readUInt32BE(16), size);
    assert.equal(bytes[25], 6, 'Favicon frames must keep their alpha channel');
    return { size, bytes };
  });
  const directory = Buffer.alloc(6 + 16 * images.length);
  directory.writeUInt16LE(1, 2);
  directory.writeUInt16LE(images.length, 4);
  let offset = directory.length;
  images.forEach(({ size, bytes }, index) => {
    const entry = 6 + index * 16;
    directory[entry] = size;
    directory[entry + 1] = size;
    directory.writeUInt16LE(1, entry + 4);
    directory.writeUInt16LE(32, entry + 6);
    directory.writeUInt32LE(bytes.length, entry + 8);
    directory.writeUInt32LE(offset, entry + 12);
    offset += bytes.length;
  });
  files.set(
    'brand/icons/favicon.ico',
    Buffer.concat([directory, ...images.map(({ bytes }) => bytes)]),
  );

  // Tight transparent header marks (the docs site logo) in dark and light ink.
  files.set('brand/logo/opensignet-mark.svg', Buffer.from(markSvg(MARK_INK)));
  files.set('brand/logo/opensignet-mark-on-dark.svg', Buffer.from(markSvg(MARK_INK_ON_DARK)));

  for (const [output, bytes] of files) {
    const file = resolve(repositoryRoot, output);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, bytes);
  }

  for (const file of refreshed) {
    manifest.files[file] = assetHash(file, readFileSync(resolve(repositoryRoot, file)));
  }
  manifest.files = Object.fromEntries(
    Object.entries(manifest.files).sort(([a], [b]) => a.localeCompare(b)),
  );
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  // The apps serve generated copies of brand/; refresh them before verifying.
  syncBrand();
  verifyAssets();
  return {
    socialBytes: social.length,
    iconBytes: files.get('brand/icons/favicon.ico')?.length ?? 0,
    width: encoded.width ?? 0,
    height: encoded.height ?? 0,
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const refresh = process.argv.includes('--refresh-rendered') ? RENDERED_BRAND_FILES : [];
  console.log(await generateWebAssets({ refresh }));
}
